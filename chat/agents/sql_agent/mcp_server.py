"""Request-scoped MCP server for authorized SQL-agent tools."""

from typing import Any

from mcp import types
from mcp.server import Server
from sqlalchemy.orm import Session

from chat.agents.sql_agent.query_executor import execute_scoped_sql
from chat.agents.sql_agent.schemas import SQLAgentError
from chat.schemas import ChatFilters
from middleware.models import User

SERVER_NAME = "marketing-intelligence-sql-agent"
SERVER_VERSION = "1.0.0"
SCHEMA_DESCRIPTION = """\
Approved sales analytics schema:
- sites: id, name, currency
- sales_records: id, site_id, product_id, order_id, sale_date, quantity, gross_revenue, discount
- products: id, site_id, name, sku, category, unit_price
Every query uses sales_records and sites; products is optional. Revenue is gross_revenue
minus discount. Authenticated-user, date, site, and product scope is injected by the
server and must not be generated by the model.
"""


def create_sql_agent_mcp_server(
    db: Session,
    user: User,
    filters: ChatFilters,
) -> Server[Any, Any]:
    """Create an MCP server whose tools are scoped to one authenticated request."""
    server: Server[Any, Any] = Server(
        SERVER_NAME,
        version=SERVER_VERSION,
        instructions=(
            "Expose only approved, read-only sales analytics schema and query tools. "
            "All query execution is scoped to the authenticated user and selected filters."
        ),
    )

    @server.list_tools()
    async def list_tools() -> list[types.Tool]:
        return [
            types.Tool(
                name="get_sales_schema",
                description=(
                    "Return the approved sales analytics tables and columns available "
                    "to the current request."
                ),
                inputSchema={"type": "object", "properties": {}, "additionalProperties": False},
                outputSchema={
                    "type": "object",
                    "properties": {
                        "schema": {"type": "string"},
                    },
                    "required": ["schema"],
                    "additionalProperties": False,
                },
                annotations=types.ToolAnnotations(readOnlyHint=True, openWorldHint=False),
            ),
            types.Tool(
                name="execute_readonly_sql",
                description=(
                    "Validate and execute one approved read-only SELECT query. The server "
                    "injects authenticated-user and selected filter constraints and returns "
                    "bounded rows."
                ),
                inputSchema={
                    "type": "object",
                    "properties": {
                        "sql": {"type": "string", "minLength": 1, "maxLength": 4000},
                    },
                    "required": ["sql"],
                    "additionalProperties": False,
                },
                annotations=types.ToolAnnotations(readOnlyHint=True, openWorldHint=False),
            ),
        ]

    @server.call_tool()
    async def call_tool(
        name: str,
        arguments: dict[str, Any],
    ) -> dict[str, Any] | types.CallToolResult:
        if name == "get_sales_schema":
            return {"schema": SCHEMA_DESCRIPTION}
        if name != "execute_readonly_sql":
            return types.CallToolResult(
                content=[
                    types.TextContent(type="text", text="Unknown SQL-agent MCP tool.")
                ],
                isError=True,
            )

        sql = arguments.get("sql")
        if not isinstance(sql, str):
            return types.CallToolResult(
                content=[
                    types.TextContent(type="text", text="The SQL tool requires a query.")
                ],
                isError=True,
            )
        try:
            return execute_scoped_sql(db, user, filters, sql)
        except SQLAgentError as error:
            return types.CallToolResult(
                content=[types.TextContent(type="text", text=str(error))],
                isError=True,
            )

    return server
